def step_transmission(eng: Engine, out: dict) -> None:
    book = eng.current()
    centre = float(book.get("nii.transmission.target"))
    t = bank_terms(eng, book)
    lo, hi = (round(target_of(t, x), 6) for x in TRANSMISSION_BANK_AXIS)

    def ok(x):
        return _solved(eng.solve(eng.current({"nii.transmission.target": x}), eng.facts, eng.bridge), x)

    while hi > centre and not ok(hi):
        hi = round(hi - 0.001, 6)
    while lo < centre and not ok(lo):
        lo = round(lo + 0.001, 6)
    rows = {}
    world, key = level_world(book), float(book.get(NIM_KEY))
    drift = 0.0
    for name, x in (("low", lo), ("centre", centre), ("high", hi)):
        tr = eng.solve(eng.current({"nii.transmission.target": x}), eng.facts, eng.bridge)
        gap = _floor_headroom(book, tr)
        drift = max(drift, abs(float(eng.bridge.to_mgmt_nim(float(tr.nss[world]))) - key))
        rows[name] = {"target": x, "phi": round(tr.phi, 4), "t_real": round(tr.t_real, 9), "solved": _solved(tr, x),
                      "nss_bank": {w: round(to_bank(t, float(v), w), 5) for w, v in tr.nss.items()},
                      "pairs": {k: None if v is None else round(v, 4) for k, v in tr.pairs.items()},
                      "floor_headroom": [round(gap[0], 5), gap[1], gap[2]]}
    out["transmission"] = {"axis": [lo, hi], "level_world": world, "level_world_fixed": drift < 1e-9, "level_world_drift": drift,
                           "rows": rows}
    say(f"nii.transmission.target {centre}: ось {lo} … {hi}; мир уровня {world} " + ("неподвижен" if drift < 1e-9 else f"УХОДИТ на {100 * drift:.4f} п.п."))
    for name, r in rows.items():
        say(f"   {name:6s} цель {r['target']:+.4f}: φ {r['phi']:.3f}, решено: {'да' if r['solved'] else 'НЕТ'}; Nss опр. банка "
            + ", ".join(f"{w} {100 * v:.2f} %" for w, v in r["nss_bank"].items()) + f"; запас пола {100 * r['floor_headroom'][0]:+.2f} п.п. "
            f"({r['floor_headroom'][1]}, мир {r['floor_headroom'][2]})")


def funds_cost_limit(book) -> tuple[float, str]:
    """Порог гейта funds_cost_to_key по правилу листа: наибольший квартал окна R на той же величине, что число гейта ядра (класс 4;
    Р10-1, Р10-16)."""
    quantity = "clients" if gate_clients(book) else "all"
    return FUNDS_COST_MAX[quantity], quantity


def funds_cost_worst(eng: Engine, share: float) -> float:
    """Наибольшая по мирам стоимость средств к ключевой (лет гейта) — ОЖИДАНИЕ МИРА (решения ведущего № 9, класс 2; № 10, Р10-6):
    число ядра model.levels.funds_cost_to_key(run, scope="world_expectation") — одна функция с гейтом ядра (вероятности
    P(r, s | w), книги средств — client_funds ядра по ключу checks.client_funds); своей копии формулы у листа нет. Лист судит
    ожидание мира и без ключа scope книги."""
    run = eng.grid({"nii.phi_split": share})
    node = eng.levels.funds_cost_to_key(run, scope=eng.levels.WORLD_EXPECTATION)
    return max(float(r["ratio"]) for r in node["by_world"].values())


def ends_phi_axis(eng: Engine, out: dict) -> None:
    """Ось доли φ на записанных числах центра (Р10-4): низ — наибольшее из низа оценок листа nii и порога гейта стоимости средств
    (уточнение до 1e-7, затем вверх к сетке SHARE_STEP), верх — шаг splits фазы концов; центр обязан пройти гейт."""
    splits = out.setdefault("splits", {})
    axis = splits.get("axis_phi")
    centre = float(eng.value("nii.phi_split"))
    gate = eng.current().opt(FUNDS_GATE)
    if axis is None or gate is None:
        return
    limit, quantity = funds_cost_limit(eng.current())
    out["ends"]["funds_cost_gate"] = {"max": limit, "funds": quantity}

    def worst(share: float) -> float:
        return funds_cost_worst(eng, share)

    ev_low = float(splits.get("phi_evidence", [axis[0]])[0])
    at_floor, at_centre = worst(ev_low), worst(centre)
    if at_centre > limit:
        raise RuntimeError(f"гейт стоимости средств клиентов срабатывает в центре книги: {at_centre:.4f} при пороге {limit}")
    low = round(math.ceil(ev_low / SHARE_STEP - 1e-9) * SHARE_STEP, 6)
    if at_floor > limit:
        root = bisect(lambda x: worst(x) - limit, ev_low, centre, tol=1e-7)
        low = min(centre, round(math.ceil(root / SHARE_STEP - 1e-9) * SHARE_STEP, 6))
    out["splits"]["axis_phi"] = [low, axis[1]]
    out["ends"]["phi_axis"] = {"low": low, "high": axis[1], "centre": centre, "mid_axis": round((low + axis[1]) / 2, 4),
                               "evidence": splits.get("phi_evidence"), "gate_max": limit, "gate_funds": quantity,
                               "at_low": round(worst(low), 4), "at_centre": round(at_centre, 4), "at_evidence_low": round(at_floor, 4)}
    say(f"ось доли φ: low {low}, high {axis[1]}, центр {centre} — стоимость средств к ключевой на низу {worst(low):.4f}, в центре {at_centre:.4f}, "
        f"на низу оценок {at_floor:.4f}, порог {limit}"
        f" ({'средства клиентов без К6' if quantity == 'clients' else 'средства ядра с книгой К6 — как число гейта ядра без ключа checks.client_funds'})")


def ends_level_axes(eng: Engine, out: dict) -> None:
    """Концы осей уровней: сдвиг ключей группы 2027–2029 (Р2), при котором уровень строки к её базе (та же функция level_of, что у
    центра) в слое M в 2029 году (год переходного корня) равен концу по правилу `ends_rule` (крайние кварталы окна R, крайние скользящие 4 квартала
    окна — Б3, или свидетельства центра — А2)."""
    node = {}
    for name in LEVEL_ORDER:
        cfg = LEVELS[name]
        window = level_ends(eng, name)
        base = eng.value(cfg["path"])
        group = cfg["groups"][0]
        year = int(group[-1][:4])

        def miss(shift, goal, base=base, group=group, year=year, cfg=cfg, name=name):
            d = dict(base)
            d.update({k: float(base[k]) + shift for k in group})
            if "2027Q1" in d and "2027" in d:                # книга прежней формы (ключ года при кварталах — среднее)
                d["2027"] = sum(d[k] for k in ("2027Q1", "2027Q2", "2027Q3", "2027Q4")) / 4
            run = eng.grid({cfg["path"]: d})
            return level_of(eng, run, market_prob(run), name, year) - goal

        lo = bisect(lambda x: miss(x, window[0]), -0.30, 0.05)
        hi = bisect(lambda x: miss(x, window[1]), -0.05, 0.40)
        # ПРАВКА 21.10.2026 (Р4-3; итог скептика econ3-classes круга 4, класс 4 в инструменте): концы — 4 знака (центр у края
        # скользящих 4 кварталов не округляется в 0), охват центра концами сверяет описание на НЕокруглённых числах (low_raw, high_raw)
        node[name] = {"low": round(lo, 4), "high": round(hi, 4), "low_raw": lo, "high_raw": hi,
                      "window": [round(window[0], 6), round(window[1], 6)], "year": year, "base": cfg["base"], "ends_rule": cfg["ends_rule"]}
        say(f"ось уровня {cfg['path']} (ключи {group[0]}–{group[-1]}): low {round(lo, 4)}, high {round(hi, 4)} — уровень {year} года "
            f"{100 * window[0]:.3f} и {100 * window[1]:.3f} % к {BASE_WORDS[cfg['base']]} (правило концов {cfg['ends_rule']})")
    out["ends"]["level_axes"] = node


def m13_scheme_of(fees_base, shares_raw) -> tuple[str, dict]:
    """Схема весов М13 по ключам книги (Р4-1, Р4-2; класс 1 — франшиза в одном месте): доли франшиз страхования и комиссий в
    базе расходов → «/share»; только комиссий → «/share_f»; без долей — франшиза на рубль базы комиссий словом (loans, iea).
    → (центр, {low, high})."""
    sh = {str(k): float(v) for k, v in (shares_raw or {}).items() if float(v) > 0}
    if sh.get("insurance", 0.0) > 0:
        suffix = "share"
    elif sh.get("fees", 0.0) > 0:
        suffix = "share_f"
    elif isinstance(fees_base, str) and fees_base in ("loans", "iea"):
        suffix = fees_base
    else:
        raise RuntimeError(f"база комиссий {fees_base!r} без доли франшизы в базе расходов: франшиза комиссий в весах М13 листа "
                           "идёт только за словом loans или iea — смесь и веса книг требуют opex.line_shares.fees (Р4-2)")
    return f"mid/{suffix}", {"low": f"loans/{suffix}", "high": f"balance/{suffix}"}


def m13_scheme(eng: Engine) -> tuple[str, dict]:
    fees = book_opt(eng, LINE_BASE_PATHS["fees"])
    fees = str(eng.value("volumes.link_base") or "loans") if fees is None else fees
    return m13_scheme_of(fees, book_opt(eng, "opex.line_shares"))


def m13_line_shares(name: str) -> dict:
    """Доли франшиз в базе расходов схемы листа m13_cost_bases.py (тип А — среднее окон, 4 знака; решения ведущего № 11, раздел А:
    «франшизы» — статистика окна; было — середина окон) — opex.line_shares книги."""
    kw = json.loads(M13_SHEET.read_text(encoding="utf-8"))["kernel_weights"][name]
    out = {}
    if "line_fees" in kw:
        out["fees"] = round(float(kw["line_fees"]["mean"]), 4)
        out["insurance"] = round(float(kw["line_ins"]["mean"]), 4)
    return out


def m13_weights(name: str) -> dict:
    """Веса книг схемы листа m13_cost_bases.py (тип А — среднее окон, запись 4 знака; решения ведущего № 11, раздел А; было —
    середина окон); корпоративный кредит — 1."""
    kw = json.loads(M13_SHEET.read_text(encoding="utf-8"))["kernel_weights"][name]
    w = {CORP_BOOK: 1.0}
    for g, books in M13_GROUPS:
        for b in books:
            w[b] = round(float(kw[g]["mean"]), 4)
    return w


def ends_m13_axis(eng: Engine, out: dict) -> None:
    """Концы оси-связки весов М13: веса конца (лист) и корни расходов 2026–2029, выведенные на них тем же правилом, что в
    центре (_solve_line: рост г/г года якоря по правилу года якоря; уровень к взвешенной базе конца в 2029 году = окну R на той
    же базе). Подмены центра восстанавливаются."""
    saved, goals, evid = copy.deepcopy(eng.overrides), dict(eng.level_goals), dict(eng.level_evidence)
    node = {}
    try:
        for end, scheme in m13_scheme(eng)[1].items():
            w = m13_weights(scheme)
            eng.overrides = copy.deepcopy(saved)
            eng.overrides["opex.volume_weights"] = w
            roots = _solve_line(eng, "opex")
            traj = rounded_traj("opex", eng.value("opex.real_growth"), roots)
            eng.overrides["opex.real_growth"] = level_traj("opex", {}, roots)
            vals = {f"opex.volume_weights.{b}": w[b] for b in w if b != CORP_BOOK}
            vals.update({f"opex.real_growth.{k}": traj[k] for k in _root_keys("opex")})
            aside: dict = {}
            end_share_roots(eng, axis_by_first(eng, "opex.volume_weights.auto") or {"name": "М13", "paths": []}, vals, aside, end)   # Р8-6
            node[end] = vals
            if aside:
                node[f"{end}_kappa"] = aside
            say(f"ось весов М13, конец {end} ({scheme}): розница {w['auto']}, бумаги {w['securities']}, средства ФЛ {w['retail_current']}, "
                f"ЮЛ {w['corp_term']}; корни расходов 2026 {traj['2026']:+.4f}, 2027К3–2029 {traj['2028']:+.4f} (уровень окна R на базе "
                f"конца {100 * eng.level_goals['opex']:.3f} %)")
    finally:
        eng.overrides, eng.level_goals, eng.level_evidence = saved, goals, evid
    out["ends"]["m13_axis"] = node


LINE_ROOT_PATHS = {"fees": "fees.growth_vs_wages", "ins": "other.insurance_growth_vs_wages", "opex": "opex.real_growth"}
LINK_PATHS = {"fees": "fees.volume_link", "ins": "other.insurance_volume_link", "opex": "opex.volume_link"}
LINK_AXIS_FIRST = "other.insurance_volume_link"          # Р7-3: ось-связка связи страхования с базой (первый путь — адрес оси)


def line_link(eng: Engine, name: str) -> float:
    """Связь строки с объёмом своей базы (книга с подменами листа); нет ключа — 0 (М§4.7)."""
    v = book_opt(eng, LINK_PATHS[name])
    return 0.0 if v is None else float(v)


def _root_keys(name: str) -> list[str]:
    """Ключи корней строки, которые несёт связка конца оси (переход 2026–2029; LT и LT_from — нет)."""
    traj = level_traj(name, {}, {"anchor": 0.0, "lt": 0.0, **{f"g{i}": 0.0 for i in range(len(LEVELS[name]["groups"]))}})
    keys = [k for k in traj if k not in ("LT", "LT_from") and int(k[:4]) <= NEAR_LAST_YEAR]
    # ключ года при квартальных ключах того же года — среднее кварталов: связка его не несёт (схема книги, М§0.4)
    return [k for k in keys if not (len(k) == 4 and f"{k}Q1" in traj)]


def base_axis(eng: Engine, name: str):
    """Ось-связка базы строки на долях смеси (К2б; Р4-1, Р4-2) — по первому пути «<база>.mix.»; нет — None."""
    head = LINE_BASE_PATHS[name] + ".mix."
    for ax in eng.book.get("valuation.uncertainty.axes"):
        if ax["kind"] == "bundle" and str(ax["paths"][0]).startswith(head):
            return ax
    return None


def base_axis_carries_opex(ax: dict, has_share: bool) -> bool:
    """Несёт ли ось базы строки корни расходов в самой связке (решения ведущего № 5, Р5-4; ключ ядра bundle_compose: additive —
    связки складываются на общем пути): пути оси — ВСЕ ключи корней расходов `_root_keys('opex')` — несёт (конец оси пишет их
    вместе с долями смеси и корнями строки); ни одного — не несёт, корни печатаются рядом ({конец}_opex, прежняя запись);
    часть — остановка листа: конец связки вышел бы без части корней. Несёт, а доли франшизы строки в базе расходов нет —
    остановка: корни расходов на этом конце не выводятся."""
    keys = [f"{LINE_ROOT_PATHS['opex']}.{k}" for k in _root_keys("opex")]
    paths = {str(p_) for p_ in ax["paths"]}
    have = [k for k in keys if k in paths]
    if not have:
        return False
    if len(have) != len(keys):
        raise RuntimeError(f"ось «{ax['name']}» несёт часть корней расходов ({', '.join(have)}) из {', '.join(keys)} — "
                           "связка базы несёт все корни расходов или ни одного (Р5-4)")
    if not has_share:
        raise RuntimeError(f"ось «{ax['name']}» несёт корни расходов, а доли франшизы строки в базе расходов "
                           "(opex.line_shares) нет — корни расходов на концах оси не выводятся (Р5-4)")
    return True


def ends_base_axes(eng: Engine, out: dict) -> None:
    """Концы осей-связок баз строк (решения ведущего № 4, Р4-1, Р4-2; проход ядра 3, К2б): доли смеси конца из книги и корни
    строки 2026–2029, выведенные на них правилом центра (уровень строки к базе конца — те же свидетельства на базе конца); если
    у строки доля франшизы в базе расходов (opex.line_shares) — и корни расходов: франшиза идёт за той же базой (класс 1). Ось
    меряет распределение строки по базам, а не её уровень. Нет оси в книге — шаг пуст (книга без К2б). Корни расходов конца
    связка несёт сама, если её пути — все ключи корней расходов (Р5-4, `base_axis_carries_opex`); иначе — запись рядом."""
    node = {}
    saved, goals, evid = copy.deepcopy(eng.overrides), dict(eng.level_goals), dict(eng.level_evidence)
    try:
        for name in ("fees", "ins"):
            ax = base_axis(eng, name)
            if ax is None:
                continue
            path = LINE_BASE_PATHS[name]
            lines = [name] + (["opex"] if name in line_shares(eng) else [])
            carry_opex = base_axis_carries_opex(ax, "opex" in lines)
            node[name] = {}
            for end in ("low", "high"):
                eng.overrides = copy.deepcopy(saved)
                mix = book_opt(eng, path)
                vals = {}
                for p_ in ax["paths"]:
                    if p_.startswith(path + ".mix."):
                        comp, field = p_[len(path) + 5:].rsplit(".", 1)
                        mix["mix"][comp][field] = float(ax[end][p_])
                        vals[p_] = float(ax[end][p_])
                eng.overrides[path] = mix
                sync_line_bases(eng)
                opex_roots = {}
                aside: dict = {}
                for i, ln in enumerate(lines):
                    eng.level_goals.pop(ln, None)
                    eng.level_evidence.pop(ln, None)
                    roots = _solve_line(eng, ln)
                    traj = rounded_traj(ln, eng.value(LINE_ROOT_PATHS[ln]), roots)
                    eng.overrides[LINE_ROOT_PATHS[ln]] = level_traj(ln, {}, roots)
                    got = {f"{LINE_ROOT_PATHS[ln]}.{k}": traj[k] for k in _root_keys(ln)}
                    # корни расходов связка базы несёт, только если её пути — все ключи корней расходов: их путь водит и
                    # связка М13, и ядро складывает связки на общем пути (Р5-4, bundle_compose: additive); иначе — печатаются
                    # рядом (остаток класса 4 на конце оси базы, для цены)
                    (opex_roots if ln == "opex" and not carry_opex else vals).update(got)
                    if i == 0:                      # Р8-6: κ конца — до корней расходов (смесь слоя M на конце — за базой строки)
                        end_share_roots(eng, ax, vals, aside, end)
                if len(lines) > 1:                  # κ после корней расходов конца (обратная связь через капитал)
                    end_share_roots(eng, ax, vals, aside, end)
                node[name][end] = vals
                if opex_roots:
                    node[name][f"{end}_opex"] = opex_roots
                if aside:
                    node[name][f"{end}_kappa"] = aside
                say(f"ось базы {path}, конец {end}: " + ", ".join(f"{k.split('.')[-1] if 'mix' not in k else k[len(path) + 5:]} {v:g}"
                                                                    for k, v in vals.items()))
    finally:
        eng.overrides, eng.level_goals, eng.level_evidence = saved, goals, evid
        sync_line_bases(eng)
    out["ends"]["base_axes"] = node


def ends_link_axis(eng: Engine, out: dict) -> None:
    """Концы оси-связки связи страхования с базой (решения ведущего № 7, Р7-3; класс 4 — как у осей баз, Р4-1, Р6-7): связь конца из
    книги и корни строки 2026–2029, выведенные на ней правилом центра (рост г/г года якоря — по правилу года якоря; уровень к своей
    базе в слое M в 2029 году — центр). Ось меряет долю «кредитного» страхования в строке, а не уровень строки. Нет оси — шаг пуст."""
    ax = axis_by_first(eng, LINK_AXIS_FIRST)
    if ax is None:
        return
    saved, goals, evid = copy.deepcopy(eng.overrides), dict(eng.level_goals), dict(eng.level_evidence)
    node = {}
    try:
        for end in ("low", "high"):
            eng.overrides = copy.deepcopy(saved)
            link = float(ax[end][LINK_AXIS_FIRST])
            eng.overrides[LINK_AXIS_FIRST] = link
            roots = _solve_line(eng, "ins")
            traj = rounded_traj("ins", eng.value(LINE_ROOT_PATHS["ins"]), roots)
            eng.overrides[LINE_ROOT_PATHS["ins"]] = level_traj("ins", {}, roots)
            vals = {LINK_AXIS_FIRST: link}
            vals.update({f"{LINE_ROOT_PATHS['ins']}.{k}": traj[k] for k in _root_keys("ins")})
            aside: dict = {}
            end_share_roots(eng, ax, vals, aside, end)     # Р8-6: κ конца связи тем же правилом (на конце «1» ядро его не читает)
            node[end] = vals
            if aside:
                node[f"{end}_kappa"] = aside
            say(f"ось связи страхования, конец {end}: связь {link:g}; корни 2026 {traj['2026']:+.4f}, 2027К1 {traj['2027Q1']:+.4f}, "
                f"2028–2029 {traj['2028']:+.4f} (уровень к базе в слое M в 2029 году — центр {100 * eng.level_goals['ins']:.3f} %)")
    finally:
        eng.overrides, eng.level_goals, eng.level_evidence = saved, goals, evid
    out["ends"]["link_axis"] = node


