def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description="вывод на ядре чисел книги Совкомбанка")
    ap.add_argument("--book", type=Path, default=None)
    ap.add_argument("--facts", type=Path, default=None)
    ap.add_argument("--steps", default=",".join(STEPS), help="шаги через запятую: " + ", ".join(STEPS))
    ap.add_argument("--rounds", type=int, default=6)
    ap.add_argument("--tol", type=float, default=1e-4)
    ap.add_argument("--no-write", action="store_true")
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--start", type=Path, default=None)
    a = ap.parse_args(argv)
    steps = [s.strip() for s in a.steps.split(",") if s.strip()]
    unknown = [s for s in steps if s not in STEPS]
    if unknown:
        print("незнакомые шаги:", ", ".join(unknown))
        return 1
    out: dict = {}
    try:
        eng = Engine(a.book, a.facts)
        if a.start is not None:
            apply_written(eng, json.loads(a.start.read_text(encoding="utf-8"))["keys"])
        book = eng.book
        try:
            constrained = bool(book.get("capital.growth_constraint.enabled"))
        except eng.BookError:
            constrained = False
        linked = [s for s in steps if s in LINKED]
        if not constrained and linked:
            print("ВНИМАНИЕ: ограничение роста в книге выключено — числа выводятся на клетке без ограничения")
        print(f"книга {book.get('meta.version')} от {book.get('meta.date')}, якорь {book.get('meta.anchor_period')}; шаги: " + " → ".join(steps))
        for s in steps:
            if s not in linked and s not in ("transmission", "ends"):
                RUNNERS[s](eng, out)
        history = []
        if linked:
            before = flat(eng)
            for i in range(1, max(1, a.rounds) + 1):
                print(f"— круг {i} связанных шагов —")
                for s in linked:
                    RUNNERS[s](eng, out)
                after = flat(eng)
                change, where = worst_change(before, after)
                history.append({"round": i, "max_relative_change": change, "at": where})
                print(f"   наибольшее изменение за круг: {change:.2e} ({where})")
                before = after
                if change < a.tol:
                    break
            out["convergence"] = {"tol": a.tol, "rounds": history, "converged": history[-1]["max_relative_change"] < a.tol}
            if not out["convergence"]["converged"]:
                print(f"ВНИМАНИЕ: за {len(history)} кругов сходимость {a.tol:g} не достигнута")
            keys = written(eng, steps)
            apply_written(eng, keys)
            if "share_roots" in steps and (share_root_lines(eng) or driver_root_lines(eng)):
                # Р8-6: κ — неподвижная точка на ЗАПИСАННЫХ (округлённых) ключах прочих шагов: округление корней строк до записи
                # двигает путь баланса (обратная связь через капитал) на 1e-5 κ — больше точности записи κ (1e-6)
                out["share_roots_frozen"] = solve_share_roots(eng)
                keys = written(eng, steps)
                apply_written(eng, keys)
            frozen_check(eng, out)
            diagnostics(eng, out)
            out["keys"] = keys
            if "level" in steps:
                step_level(eng, out)
        if "transmission" in steps:
            step_transmission(eng, out)
        if "ends" in steps:
            if not linked:
                out["keys"] = {}
            out["ends"] = {}
            print("— концы осей и проверки —")
            ends_phi_axis(eng, out)
            ends_level_axes(eng, out)
            ends_m13_axis(eng, out)
            ends_base_axes(eng, out)
            ends_link_axis(eng, out)
            ends_cor_intensity(eng, out)
            ends_perimeter(eng, out)
            ends_wholesale(eng, out)
            ends_window(eng, out)
            ends_cir_lt(eng, out)
            ends_variants(eng, out)
            ends_need(eng, out)
            ends_roe_bound(eng, out)
            ends_kappa_check(eng, out)
        if linked:
            print_keys(out["keys"])
        out["evaluations"] = {"cells": eng.evaluations, "grids": eng.grids}
    except NeedCore as exc:
        print(str(exc))
        return 2
    except Exception as exc:                                    # noqa: BLE001
        import traceback
        traceback.print_exc()
        print(f"ОТКАЗ вывода ({type(exc).__name__}): {exc}")
        return 1
    if not a.no_write:
        target = a.out or HERE / "out" / "derive_out.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"готово: прогонов модальной клетки {eng.evaluations}, сеток {eng.grids}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
