def axis_by_first(eng: Engine, first: str, kind: str = "bundle"):
    """Ось книги вида `kind` с первым путём `first`; нет — None."""
    for ax in eng.book.get("valuation.uncertainty.axes"):
        if ax["kind"] == kind and str(ax["paths"][0]) == first:
            return ax
    return None


def ends_cor_intensity(eng: Engine, out: dict) -> None:
    """Концы оси-связки интенсивности состава окон CoR (решения ведущего № 3, Р3, п. 3; № 4, Р4-13; № 6, Р6-7): каждый ключ пути
    режима в связке на конце — ключ центра × I_mid / I_источника своего окна (факты credit_products.intensity.<окно>, поле keys:
    центр ключа = (уровень окна + κ × Δrr) / I_mid, конец — тот же уровень на интенсивности одного источника). Читает ключи режимов
    ЦЕНТРА книги (с подменами листа): новый центр ключей режимов — новые концы. Ключ без окна интенсивности — остановка. Нет оси —
    шаг пуст."""
    ax = axis_by_first(eng, INTENSITY_AXIS_FIRST)
    if ax is None:
        return
    groups = {}
    for name, node in eng.facts.file("credit_products")["intensity"].items():
        for k in node.get("keys") or []:
            groups[str(k)] = (name, node)
    missing = [p for p in ax["paths"] if p not in groups]
    if missing:
        raise RuntimeError(f"ось интенсивности окон CoR: у ключей {missing} нет окна интенсивности (credit_products.intensity.*.keys)")
    node = {"low": {}, "high": {}, "windows": {}}
    for p in ax["paths"]:
        name, g = groups[p]
        centre = float(book_opt(eng, p))
        mid = float(g["mid"]["v"])
        for end, src in INTENSITY_ENDS.items():
            node[end][p] = round(centre * mid / float(g[src]["v"]), 6)
        node["windows"][p] = name
    out["ends"]["cor_intensity"] = node
    lt = INTENSITY_AXIS_FIRST
    say(f"ось интенсивности окон CoR ({len(ax['paths'])} ключей режимов): {lt} {book_opt(eng, lt):.6f} — низ (МСФО) {node['low'][lt]:.6f}, "
        f"верх (датабук) {node['high'][lt]:.6f}")


def _perim_lines(ax: dict) -> list[str]:
    """Строки листа, чьи корни несёт ось периметра (по путям оси), в порядке вывода центра."""
    have = {name for name in LEVEL_ORDER for p in ax["paths"] if str(p).startswith(LINE_ROOT_PATHS[name] + ".")}
    return [name for name in LEVEL_ORDER if name in have]


def ends_perimeter(eng: Engine, out: dict) -> None:
    """Концы осей-связок периметра окна R (решения ведущего № 5, Р5-3; № 6, Р6-7): ряд поправок периметра (узел фактов perimeter) на
    конце связки (прочие связки — как в запуске), корни строк, которые несёт ось (страхование и/или расходы 2026–2029 со ступенями
    2027К1–К2), выведены на нём правилом центра (_solve_line — то же, что ends_base_axes: один проход строк на записанных числах
    центра). Прежде — восемь сухих перевыводов концов вне команды (var/i5/perim_collect.py): там же круг связанных шагов до
    сходимости; остаток — дрожание корней комиссий ±0,0001 и прочих выведенных чисел конца (концы осей уровня, цель cir_lt) —
    связка их не несёт (класс 4, назван, Р5-3). Связка, чей конец держит запуск (SVCB_PERIMETER_ENDS — развилка конца), и ряд
    выключенный (off) — ось вырождается в центр запуска. Нет оси в книге — шаг пуст."""
    env = PERIM_INFO.get("ends") if not PERIM_INFO.get("off") else "off"
    env = {} if env in (None, "центр") else env
    node = {}
    saved, goals, evid = copy.deepcopy(eng.overrides), dict(eng.level_goals), dict(eng.level_evidence)
    try:
        for g, first in PERIM_AXES.items():
            ax = axis_by_first(eng, first)
            if ax is None:
                continue
            if not str(ax["name"]).startswith(PERIM_AXIS_NAME):
                raise RuntimeError(f"ось с первым путём {first} — не ось периметра ({ax['name']!r}): адреса PERIM_AXES листа устарели")
            lines = _perim_lines(ax)
            node[g] = {}
            for end in ("low", "high"):
                eng.overrides = copy.deepcopy(saved)
                if env == "off" or g in env:                 # ряд выключен или конец связки держит запуск — ось в центре запуска
                    vals = {p: float(book_opt(eng, p)) for p in ax["paths"]}
                    node[g][end] = {"values": vals, "degenerate": True}
                    continue
                sync_perimeter(eng, {**env, g: end})
                trajs = {}
                for ln in lines:
                    eng.level_goals.pop(ln, None)
                    eng.level_evidence.pop(ln, None)
                    roots = _solve_line(eng, ln)
                    eng.overrides[LINE_ROOT_PATHS[ln]] = level_traj(ln, {}, roots)
                    trajs[ln] = rounded_traj(ln, eng.value(LINE_ROOT_PATHS[ln]), roots)
                vals = {}
                for p in ax["paths"]:
                    if str(p).startswith((SHARE_ROOTS + ".", DRIVER_ROOTS + ".")):   # Р8-6, Р9-1: κ и ρ конца — ниже, тем же правилом
                        continue
                    ln = next(n for n in lines if str(p).startswith(LINE_ROOT_PATHS[n] + "."))
                    vals[p] = float(trajs[ln][str(p)[len(LINE_ROOT_PATHS[ln]) + 1:]])
                aside: dict = {}
                end_share_roots(eng, ax, vals, aside, end)
                vals = {str(p): vals[str(p)] for p in ax["paths"]}   # порядок путей связки
                node[g][end] = {"values": vals, "degenerate": False, **({"kappa": aside} if aside else {})}
            say(f"ось периметра {g} ({', '.join(lines)}): " + "; ".join(
                f"{end} " + ", ".join(f"{p.replace('other.insurance_growth_vs_wages', 'ins').replace('opex.real_growth', 'opex')} {v:g}"
                                      for p, v in node[g][end]["values"].items() if p.endswith(("2026", "2027Q1", "2029")))
                for end in ("low", "high")))
    finally:
        eng.overrides, eng.level_goals, eng.level_evidence = saved, goals, evid
        if env == "off":
            sync_perimeter(eng)
        else:
            sync_perimeter(eng, dict(env))
    out["ends"]["perimeter_axes"] = node


def ends_wholesale(eng: Engine, out: dict) -> None:
    run = eng.grid()
    book = run.ctx.book
    tl = run.ctx.timeline
    ends = [q for q in (tl.quarters_of_year(y)[-1] for y in run.cells[0].years) if 1 <= q <= tl.Q]
    ctx = run.ctx
    # величина — та же, что число гейта ядра wholesale_share (класс 4; Р10-1 — при ключе ядра checks.client_funds: clients)
    share = lambda c, q: float(c.quarters["wholesale"][q]) / (gate_funds(ctx, c, q) + float(c.quarters["wholesale"][q]))  # noqa: E731
    modal = run.cell(*eng.modal_cell(book, run.ctx.posterior))
    anchor = share(modal, 0)
    worst = max((max(share(c, q) for q in ends), c.label) for c in run.cells)
    low = min(min(share(c, q) for q in ends) for c in run.cells)
    # К3 (решения ведущего № 3, Р4; интеграция круга 3): при структурной доле опта s сверх неё опт идёт по нужде в обе стороны, и
    # нижняя граница доли опта — сама структурная доля s / (1 + s) (опт ≥ s × средства), а не «доля якоря минус 5 п.п.»
    # (при s ниже доли якоря правило якоря срабатывало бы на законном гашении избытка); верх — прежнее правило
    s = book.opt("volumes.wholesale_structural_to_funds")
    floor_share = None if s is None else float(s) / (1 + float(s))
    low_end = anchor - WHOLESALE_MARGIN if floor_share is None else floor_share
    corridor = [round(int(low_end * 100 + 1e-9) / 100, 2), round(-int(-(worst[0] + WHOLESALE_MARGIN) * 100 - 1e-9) / 100, 2)]
    out["ends"]["wholesale_share"] = {"funds": "clients" if gate_clients(book) else "all",
                                      "anchor": round(anchor, 4), "min": round(low, 4), "max": round(worst[0], 4), "max_cell": worst[1],
                                      "corridor": corridor, "margin": WHOLESALE_MARGIN,
                                      "structural_floor": None if floor_share is None else round(floor_share, 6)}
    say(f"checks.wholesale_share по правилу: {corridor}    # доля якоря {100 * anchor:.1f} %; по клеткам {100 * low:.1f}…{100 * worst[0]:.1f} % ({worst[1]})")


def ends_window(eng: Engine, out: dict) -> None:
    """Поля окна фактов checks.window_backtest: CoR окна R на составе якоря (credit_products, Р3) и C/I окна R (cir_exact)."""
    quarters = eng.facts.file("mgmt_quarterly")["quarters"]
    keys = sorted(quarters)
    window = [q for q in keys if R_WINDOW[0] <= q <= R_WINDOW[1]]
    node: dict = {"quarters": window}
    # CoR окна — НА СОСТАВЕ ЯКОРЯ (решения ведущего № 3, Р3, п. 7): Σ w0_b × CoR_b,q по кварталам окна (факты
    # credit_products: датабук по книгам, доли якоря); гейт судит cor_mix0 (CoR клеток на составе якоря) — одна величина.
    # Окно на своём составе (cor_exact, 2,16–3,69 %) — справочно в записи (cor_window_composition).
    cp = eng.facts.file("credit_products")["quarters"]
    # ПРАВКА 22.10.2026 (решения ведущего № 6, Р6-2, на класс): «среднее окна» — среднее скользящих 4 кварталов (равный вес
    # календарных кварталов), было — среднее 9 кварталов (2К трижды); поля печати гейта, числа модели не меняют
    for name, vals in (("cor", [float(cp[q]["on_anchor"]["v"]) for q in window]),
                       ("cor_window_composition", [float(quarters[q]["cor_exact"]["v"]) for q in window]),
                       ("cir", [float(quarters[q]["cir_exact"]["v"]) for q in window])):
        node[name] = {"min": round(min(vals), 4), "max": round(max(vals), 4), "mean": round(roll4_mean(vals), 4),
                      "min_quarter": window[vals.index(min(vals))], "max_quarter": window[vals.index(max(vals))]}
    # Маржа окна R — мерка слоя «рыночные ставки как есть» (решения ведущего № 2, А5: мир N — окно L, слой M — окно R) В ТОЙ ЖЕ
    # ВЕЛИЧИНЕ, что печатает ядро (ключ ядра: ЧПМ движка с финрасходами страхования / мост b): кварталы окна — ЧПМ движка фактов
    # (bridge_mgmt_ifrs.nim.history.engine) / b. Опр. банка — лист приёмки (acceptance.py). Доля кредитов в процентных активах окна
    # R — средние остатки кварталов (balance.history: кредитные книги / процентные активы движка), сумма к сумме.
    hist = {r["period"]: r for r in eng.facts.file("bridge_mgmt_ifrs")["nim"]["history"]}
    b = float(eng.bridge.nim_value)
    vals = [float(hist[q]["engine"]["v"]) / b for q in window]
    node["nim"] = {"min": round(min(vals), 4), "max": round(max(vals), 4), "mean": round(roll4_mean(vals), 4),
                   "min_quarter": window[vals.index(min(vals))], "max_quarter": window[vals.index(max(vals))]}
    bal = eng.facts.file("balance")["history"]
    ends = sorted(bal)
    loans, iea = [], []
    for qn in window:
        prev = ends[ends.index(qn) - 1]
        loans.append((float(bal[prev]["loans"]["v"]) + float(bal[qn]["loans"]["v"])) / 2)
        iea.append((float(bal[prev]["iea"]["v"]) + float(bal[qn]["iea"]["v"])) / 2)
    roll = [sum(loans[i:i + 4]) / sum(iea[i:i + 4]) for i in range(len(loans) - 3)]
    node["loans_share"] = round(sum(roll) / len(roll), 4)          # Р6-2: среднее скользящих 4 кварталов (сумма к сумме внутри)
    out["ends"]["window"] = node
    say(f"окно R {window[0]}–{window[-1]}: " + "; ".join(f"{n} {100 * node[n]['min']:.2f}…{100 * node[n]['max']:.2f} % (среднее {100 * node[n]['mean']:.2f})"
                                                         for n in ("cor", "cir", "nim")) + f" (CoR — на составе якоря, на своём составе "
        f"{100 * node['cor_window_composition']['min']:.2f}…{100 * node['cor_window_composition']['max']:.2f} %; ЧПМ — ключ ядра); доля кредитов в ПА {100 * node['loans_share']:.1f} %")


def ends_cir_lt(eng: Engine, out: dict) -> None:
    """Цель гейта cir_lt — К БАЗЕ М13 (решения ведущего № 4, Р4-10; итог проверок экономики круга 3, класс 4 в гейте): прежняя цель
    (C/I на составе окна R, 52,2 %) складывала уровни разных составов. Гейт ядра судит C/I слоя «рыночные ставки как есть» за годы
    from_year…последний (model.levels.cir_lt_value), поэтому цель — тот же C/I слоя при расходах, равных уровню окна R на базе М13
    (центр уровня листа): для года y — to_mgmt_cir(уровень × база М13_y / доход_y); допуск — тот же C/I на концах оси уровня
    расходов (крайние скользящие 4 квартала окна R на той же базе). Гейт срабатывает, если расходы слоя к базе М13 уходят от
    уровня окна дальше концов его оси — расходы к базе, а не состав."""
    cfg = eng.current().opt("checks.cir_lt")
    if cfg is None:
        return
    run = eng.grid()
    prob = market_prob(run)
    tl = run.ctx.timeline
    goal = eng.level_goals.get("opex")
    if goal is None:
        goal = level_goal(eng, "opex")
    lo, hi = level_ends(eng, "opex")
    br = eng.bridge
    years = [y for y in range(int(cfg["from_year"]), tl.last_year + 1)]
    rows = {}
    for y in years:
        mix = eng.levels.mix_year(run, prob, y)
        base = avg_base(eng, run, prob, y, LEVELS["opex"]["base"], "opex")
        inc = float(mix["income"])
        rows[str(y)] = {k: float(br.to_mgmt_cir(lvl * base / inc)) for k, lvl in (("centre", goal), ("low", lo), ("high", hi))}
        rows[str(y)]["layer"] = float(mix["mgmt"]["cir"])
    mean = lambda k: sum(r[k] for r in rows.values()) / len(rows)  # noqa: E731
    target = mean("centre")
    tol = max(abs(mean("high") - target), abs(target - mean("low")))
    node = {"target": round(target, 4), "tolerance": round(math.ceil(tol * 1000 - 1e-9) / 1000, 3), "years": years,
            "opex_level": round(goal, 7), "opex_ends": [round(lo, 7), round(hi, 7)], "layer_mean": round(mean("layer"), 4),
            "rows": {y: {k: round(v, 5) for k, v in r.items()} for y, r in rows.items()}}
    out["ends"]["cir_lt"] = node
    say(f"цель гейта cir_lt (Р4-10): C/I слоя M при расходах в центре уровня (тип В, А2 — середина уровня года якоря целиком и "
        f"среднего окна R; Р12-1, Р12-1а) {100 * goal:.3f} % базы М13 — {100 * target:.2f} % (упр.), "
        f"допуск {100 * node['tolerance']:.1f} п.п. (концы оси уровня расходов); C/I слоя сейчас {100 * node['layer_mean']:.2f} %")


