def normalized_line_weights(eng: Engine, w: dict) -> dict:
    """Веса книг базы строки, нормированные на квартале якоря ТЕМ ЖЕ правилом, что ядро (model.cell._weighted_history, М§4.7
    К2: ω̂_b = ω_b Σ Ē_b,0 / Σ ω_b Ē_b,0 по книгам с весом > 0; Ē_b,0 — полусумма остатков на конец квартала якоря и прошлого
    квартала). ПРАВКА 21.10.2026 (поток book4, класс 4 в листе): лист брал веса книги как есть, а ядро ведёт ряд vol_fees /
    vol_ins на нормированных весах — при неравных весах (смесь «розница … все кредиты», база по месту выручки комиссий) уровень
    окна мерился к базе в 1/norm раз меньше базы слоя M (norm 1,38 при весе юрлиц 0,5; 1,59 при весе розницы 0,17) — отсюда
    остановы проб econ3 (корень 2027К1 0,217; «корня нет»). При одинаковых весах (розница 1 или юрлица 1) norm = 1 — бит в бит."""
    bal = eng.facts.file("balance")
    hist = bal["history"]
    anchor = str(eng.facts.plain("anchor", "period"))
    ends = sorted(hist)
    prev = ends[ends.index(anchor) - 1]
    avg0 = {b: (float(bal["books"][b]["v"]) + float(hist[prev]["books"][b]["v"])) / 2 for b in w}
    norm = sum(avg0.values()) / sum(w[b] * avg0[b] for b in w)
    return {b: w[b] * norm for b in w}


