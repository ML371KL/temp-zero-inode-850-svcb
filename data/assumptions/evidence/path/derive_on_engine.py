def need_ratio(run) -> float:
    """Кредиты к средствам клиентов на конец NEED_YEAR — отношение ожиданий слоя «свой взгляд» (агрегация mix_year). Средства
    клиентов — без книг К6 (Р10-1: суждение «кредиты равны средствам клиентов» говорит о деньгах клиентов; было — средства ядра
    с книгой страховых, нужда −7,92 п.п.)."""
    q = run.ctx.timeline.quarters_of_year(NEED_YEAR)[-1]
    return own_expect(run, lambda c: c.quarters["loans"][q]) / own_expect(run, lambda c: client_funds(run.ctx, c, q))


def premium_fact_readings(eng: Engine) -> dict:
    """Прочтение «факты» премии роста средств клиентов по сегментам — та же формула, что правило центра class_checks.yaml."""
    bal = eng.facts.file("balance")

    def seg_sum(seg: str, p: str) -> float:
        node = bal["books"] if p == "anchor" else bal["history"][p]["books"]
        return sum(float(node[b]["v"] if isinstance(node[b], dict) else node[b]) for b in PREMIUM_FACT_BOOKS[seg])

    out = {}
    for seg, sector in PREMIUM_FACT_SECTOR.items():
        vals = [seg_sum(seg, a) / seg_sum(seg, b) / (1 + g) - 1 for (a, b), g in zip(PREMIUM_FACT_WINDOWS, sector)]
        out[seg] = sum(vals) / len(vals)
    return out


def premium_axis_ends(facts_readings: dict, need: float) -> dict:
    """Концы оси премии средств (класс 4, тип В): диапазон прочтений «факты» и «нужда» по сегменту в 2027 году (4 знака), 2028–2029 —
    форма книги (× 0,66 / 0,34, 4 знака) — правило концов class_checks.yaml."""
    ends = {"low": {}, "high": {}}
    for path in PREMIUM_PATHS:
        seg = path.rsplit(".", 1)[1]
        lo, hi = round(min(facts_readings[seg], need), 4), round(max(facts_readings[seg], need), 4)
        for year, share in PREMIUM_SHAPE.items():
            ends["low"][f"{path}.{year}"] = round(lo * share, 4)
            ends["high"][f"{path}.{year}"] = round(hi * share, 4)
    return ends


def ends_need(eng: Engine, out: dict) -> None:
    """«Нужда баланса»: уровень премии роста средств клиентов в форме оси книги, при котором кредиты равны средствам клиентов на
    конец NEED_YEAR в ОЖИДАНИИ СЛОЯ «СВОЙ ВЗГЛЯД» (отношение ожиданий; решения ведущего № 9, Р9-2 — PLAYBOOK §4, п. 2: ожидание,
    а не самая вероятная клетка; было — модальная клетка H/soft/mid, Р4-7) — на записанных числах, без перевывода связанных
    шагов. Нужду пишет команда (вариант funds_premium_need); центр премии книги — середина фактов и этой нужды (правило класса 6
    читает нужду из варианта формулой); одна премия на все миры — законная связь книги с ценой (class_checks.yaml)."""
    def ratio(level: float) -> float:
        ov = {}
        for path in PREMIUM_PATHS:
            traj = copy.deepcopy(dict(eng.value(path)))
            traj.update({y: level * s for y, s in PREMIUM_SHAPE.items()})
            ov[path] = traj
        return need_ratio(eng.grid(ov))

    book_ratio = need_ratio(eng.grid())
    ctx_m, cell_m = eng.cell()
    q_m = ctx_m.timeline.quarters_of_year(NEED_YEAR)[-1]
    modal_ratio = float(cell_m.quarters["loans"][q_m]) / client_funds(ctx_m, cell_m, q_m)   # печать рядом — та же величина (Р10-1)
    probes = []
    x0, x1 = 0.0, 0.05
    f0, f1 = ratio(x0) - 1.0, ratio(x1) - 1.0
    probes += [(x0, f0 + 1), (x1, f1 + 1)]
    for _ in range(10):
        if abs(f1) < 2e-4 or f1 == f0:
            break
        x0, x1, f0 = x1, x1 - f1 * (x1 - x0) / (f1 - f0), f1
        f1 = ratio(x1) - 1.0
        probes.append((x1, f1 + 1))
    readings = premium_fact_readings(eng)
    axis = premium_axis_ends(readings, round(x1, 4))
    out["ends"]["need"] = {"year": NEED_YEAR, "shape": PREMIUM_SHAPE, "level": round(x1, 4), "layer": OWN_LAYER,
                           "loans_to_funds_book": round(book_ratio, 4), "loans_to_funds_book_modal_cell": round(modal_ratio, 4),
                           "probes": [[round(a, 5), round(b, 5)] for a, b in probes],
                           "fact_readings": {k: round(v, 6) for k, v in readings.items()}, "axis": axis}
    say(f"«нужда баланса»: премия средств клиентов {100 * x1:+.2f} п.п. в 2027 году (форма {PREMIUM_SHAPE}) — кредиты равны средствам на "
        f"конец {NEED_YEAR} в ожидании слоя «свой взгляд»; при премии книги кредиты / средства {100 * book_ratio:.1f} % (модальная клетка "
        f"{100 * modal_ratio:.1f} %)")
    say("ось премии средств (класс 4, тип В — диапазон прочтений «факты» и «нужда»): " + "; ".join(
        f"{seg} 2027 {100 * axis['low'][f'volumes.funds_share_drift.{seg}.2027']:+.2f} … {100 * axis['high'][f'volumes.funds_share_drift.{seg}.2027']:+.2f} п.п. "
        f"(факты {100 * readings[seg]:+.2f})" for seg in PREMIUM_FACT_BOOKS))


def window_roe(eng: Engine, quarters) -> float:
    """ROE окна фактов без разовых (Р11-8): Σ (ni_shareholders − noncore_net) × 4 / n ÷ среднее по кварталам среднего капитала акционеров."""
    q = eng.facts.file("pnl_quarterly")["quarters"]
    hist = eng.facts.file("balance")["history"]
    allq = sorted(hist)
    fv = lambda node: float(node["v"] if isinstance(node, dict) else node)  # noqa: E731
    avg = [(fv(hist[allq[allq.index(p) - 1]]["bv_common"]) + fv(hist[p]["bv_common"])) / 2 for p in quarters]
    flow = sum(fv(q[p]["ni_shareholders"]) - fv(q[p]["noncore_net"]) for p in quarters)
    return flow * 4 / len(quarters) / (sum(avg) / len(avg))


def ends_roe_bound(eng: Engine, out: dict) -> None:
    """Р11-8: нижняя граница ROE модели (наименьший ROE слоёв по годам ROE_BOUND_YEARS) и отбор окон строк-долей по ней — печать и
    запись; отбор книги (окна правил class_checks.yaml и MODEL_WINDOWS_ONLY листа М13) против отбора правила — невязка описания."""
    from model.grid import point_probabilities
    run = eng.grid()
    layers = {"смесь точки": point_probabilities(run), "свой взгляд": own_prob(run), "слой M": market_prob(run)}
    y0, y1 = ROE_BOUND_YEARS
    roe = {name: {str(y): float(eng.levels.mix_year(run, prob, y)["roe"]) for y in range(y0, y1 + 1)} for name, prob in layers.items()}
    low = {name: min(v.items(), key=lambda kv: kv[1]) for name, v in roe.items()}
    layer, (year, bound) = min(low.items(), key=lambda kv: kv[1][1])
    windows, ok = {}, True
    for name, (qs, line, role, used) in ROE_WINDOWS.items():
        r = window_roe(eng, qs)
        inside = r >= bound
        ok &= inside == used
        windows[name] = {"roe": round(r, 4), "inside": inside, "used_by_book": used, "line": line, "role": role}
    out["ends"]["roe_bound"] = {"bound": round(bound, 4), "layer": layer, "year": int(year), "years": list(ROE_BOUND_YEARS),
                                "layers_min": {k: [int(y), round(v, 4)] for k, (y, v) in low.items()}, "windows": windows, "ok": ok}
    say(f"нижняя граница ROE модели (Р11-8): {100 * bound:.2f} % — {layer}, {year} год (наименьшие по слоям: "
        + "; ".join(f"{k} {100 * v:.2f} % ({y})" for k, (y, v) in low.items()) + ")")
    for name, w in windows.items():
        say(f"  окно {name} ({w['line']}, {w['role']}): ROE без разовых {100 * w['roe']:.2f} % — "
            f"{'в условиях модели' if w['inside'] else 'ВНЕ условий модели'}; в книге {'берётся' if w['used_by_book'] else 'не берётся'}"
            + ("" if w["inside"] == w["used_by_book"] else " — ОТБОР КНИГИ НЕ РАВЕН ПРАВИЛУ"))


def ends_kappa_check(eng: Engine, out: dict) -> None:
    """Р9-7 (решения ведущего № 9): κ на концах связок против правила на записанных числах конца — наибольшие по концам; допуск
    листа KAPPA_END_TOL (центр — 1e-5 и 2e-6, концы — 5e-5: корни конца записаны 4 знаками и двигают путь баланса)."""
    line = getattr(eng, "link_line", None)
    rows = list(eng.kappa_ends.values())
    if rows:
        rc = max(r["rule_change"] for r in rows)
        md = max((r["max_dev"] for r in rows if r["max_dev"] is not None), default=0.0)
        out["ends"]["kappa_ends"] = {"tol": KAPPA_END_TOL, "level_tol": LEVEL_END_TOL, "rule_change_max": rc, "max_dev_max": md,
                                     "ok": rc <= KAPPA_END_TOL and md <= LEVEL_END_TOL, "rows": rows}   # Р10-13: судятся оба
        say(f"κ на концах связок (Р9-7, Р10-13; на записанных числах конца): правило против записи до {rc:.1e} (допуск "
            f"{KAPPA_END_TOL:g}), невязка {'E_M[Φ] − E_M[A]/A_0' if line else 'E_M[H] − E_M[A]/A_0'} до {md:.1e} (допуск "
            f"{LEVEL_END_TOL:g}); концов {len(rows)}")
    rows = list(eng.rho_ends.values())
    if rows:                                                   # Р9-1: ρ концов — та же проверка, что κ (Р9-7, Р10-13)
        rc = max(r["rule_change"] for r in rows)
        md = max(r["max_dev"] for r in rows)
        jn = max(r["jensen"] for r in rows)
        out["ends"]["rho_ends"] = {"tol": KAPPA_END_TOL, "level_tol": LEVEL_END_TOL, "rule_change_max": rc, "max_dev_max": md,
                                   "jensen_max": jn, "ok": rc <= KAPPA_END_TOL and md <= LEVEL_END_TOL, "rows": rows}
        say(f"ρ на концах связок (Р9-1, Р10-13; на записанных числах конца): правило против записи до {rc:.1e} (допуск "
            f"{KAPPA_END_TOL:g}), невязка {'E_M[Ψ] − E_M[D]/D_0' if line else 'N^ρ,M − E_M[D]/D_0'} до {md:.1e} (допуск "
            f"{LEVEL_END_TOL:g}), Йенсен до {jn:.1e}; концов {len(rows)}")


