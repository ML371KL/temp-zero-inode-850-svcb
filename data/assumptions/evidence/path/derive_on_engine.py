def rho_of(eng: Engine, run, line: str) -> tuple[dict, float, float]:
    """ρ строки правилом листа на сетке `run` (запись 6 знаков; Р9-1): ρ_q = E_M[D_q] / E_M[D_(q−1)] / (1 + w^M_q)^(1/4) − 1 до
    2029К4 по ряду vol_end_<строка>, D_0 — уровень якоря; невязка этой сетки на ЗАПИСАННЫХ ρ (ряд подготовки прогона)
    max_q≤2029К4 |N^ρ,M_q − E_M[D_q] / D_0|, N^ρ,M_q = Π_x (1 + w^M_x)^(1/4)(1 + ρ_x); печать Йенсена max_q |E_M[К6_q] / К6_0 ÷
    E_M[D_q] / D_0 − 1| по книгам К6 строки. Строка ключа без ведомой книги — остановка листа."""
    tl = run.ctx.timeline
    prep = run.ctx.prep
    roots = getattr(prep, "driver_roots", None) or {}
    books = [b for b, (ln, _) in roots.items() if ln == line]
    if not books:
        raise RuntimeError(f"ρ строки {line}: К6 этой строкой не ведёт (ключ {DRIVER_ROOTS}.{line} без ведомой книги; Р9-1)")
    if getattr(prep, "k6_line", None) is not None:          # Р10-5: книги К6 формой строки — ρ корень г/г на концах
        return _rho_line(eng, run, line, books)
    row = DRIVER_ROOT_ROWS[line]
    if row not in run.cells[0].quarters:
        raise RuntimeError(f"ρ строки {line}: у клеток нет ряда {row} — ядро без прохода 7 (Р9-1)")
    prob = market_prob(run)
    wage = run.ctx.worlds[SHARE_ROOT_WORLD].wage
    q_end = tl.index(SHARE_ROOT_LAST)
    d0 = float(prep.driven[books[0]][0].end0)
    em = [d0] + [float(eng.levels.expect(run, prob, row, q)) for q in range(1, q_end + 1)]
    traj: dict = {tl.period(q): round(em[q] / em[q - 1] / (1 + float(wage[q])) ** 0.25 - 1, 6) for q in range(1, q_end + 1)}
    traj["LT"] = 0.0
    traj["LT_from"] = int(SHARE_ROOT_LAST[:4]) + 1
    rec = roots[books[0]][1]
    n, dev = 1.0, 0.0
    for q in range(1, q_end + 1):
        n *= (1 + float(wage[q])) ** 0.25 * (1 + float(rec[q]))
        dev = max(dev, abs(n - em[q] / d0))
    jen = 0.0
    for b in books:
        e0 = float(run.cells[0].books[b]["balance"][0])
        for q in range(1, q_end + 1):
            ek = sum(prob[c.key] * float(c.books[b]["balance"][q]) for c in run.cells)
            jen = max(jen, abs((ek / e0) / (em[q] / d0) - 1))
    return traj, dev, jen


def _rho_line(eng: Engine, run, line: str, books: list[str]) -> tuple[dict, float, float]:
    """ρ формы строки (Р10-5): правило `_line_rule` на уровне базы строки на концах кварталов D (ряд vol_end_<строка>, история —
    концы фактов ядра, prep.hist_k6_line), λ — связь строки ядра; невязка max_q≤2029К4 |E_M[Ψ_q] − E_M[D_q] / D_0| по ряду Ψ ядра
    (vol_psi_<строка>); печать «Йенсена» — книга К6 против базы: max_q |E_M[К6_q] / К6_0 ÷ E_M[D_q] / D_0 − 1| (форма строки
    держит индекс линейно по Ψ: до округления записи ρ — 0)."""
    from model.cell import END_FLOWS, LAG_END_FLOWS, PSI_FLOWS
    tl = run.ctx.timeline
    prep = run.ctx.prep
    k6 = prep.k6_line.get(line)
    if k6 is None:
        raise RuntimeError(f"ρ строки {line}: К6 этой строкой не ведёт (форма строки, Р10-5)")
    prob = market_prob(run)
    hist = prep.hist_k6_line[LAG_END_FLOWS[line]]
    end, psi = END_FLOWS[line], PSI_FLOWS[line]
    traj, _ = _line_rule(run, prob, float(k6[0]), hist, lambda c, q: c.quarters[end][q], prep.root_mult)
    q_end = tl.index(SHARE_ROOT_LAST)
    d0 = float(hist[0])
    em = {q: float(eng.levels.expect(run, prob, end, q)) / d0 for q in range(1, q_end + 1)}
    dev = max(abs(float(eng.levels.expect(run, prob, psi, q)) - em[q]) for q in range(1, q_end + 1))
    jen = 0.0
    for b in books:
        e0 = float(run.cells[0].books[b]["balance"][0])
        for q in range(1, q_end + 1):
            ek = sum(prob[c.key] * float(c.books[b]["balance"][q]) for c in run.cells)
            jen = max(jen, abs((ek / e0) / em[q] - 1))
    return traj, dev, jen


def solve_share_roots(eng: Engine) -> dict:
    """Неподвижная точка κ и ρ ОДНОЙ итерацией на подменах листа (Р8-6, Р9-1: κ, ρ → сетка с ключами → E_M[A], E_M[D] → κ, ρ) до
    SHARE_ROOT_TOL по max(Δκ, Δρ); κ и ρ — в подмены листа. Нет ни κ, ни ρ — пусто."""
    lines, r_lines = share_root_lines(eng), driver_root_lines(eng)
    rounds = []
    if not lines and not r_lines:
        return {"rounds": [0.0], "converged": True}
    for _ in range(SHARE_ROOT_ITERS):
        run = eng.grid()
        change = 0.0
        if lines:
            cur = eng.value(SHARE_ROOTS) or {}
            new = {ln: kappa_of(eng, run, ln)[0] for ln in lines}
            change = max(change, max(_kappa_change(cur.get(ln), new[ln]) for ln in lines))
        if r_lines:
            cur_r = eng.value(DRIVER_ROOTS) or {}
            new_r = {ln: rho_of(eng, run, ln)[0] for ln in r_lines}
            change = max(change, max(_kappa_change(cur_r.get(ln), new_r[ln]) for ln in r_lines))
        if lines:
            eng.overrides[SHARE_ROOTS] = {**{str(k): v for k, v in cur.items()}, **new}
        if r_lines:
            eng.overrides[DRIVER_ROOTS] = {**{str(k): v for k, v in cur_r.items()}, **new_r}
        rounds.append(change)
        if change < SHARE_ROOT_TOL:
            break
    return {"rounds": rounds, "converged": rounds[-1] < SHARE_ROOT_TOL}


def step_share_roots(eng: Engine, out: dict) -> None:
    """Корень κ номинальной части франшизы строки (Р8-6) и корень ρ номинальной части книг К6 (Р9-1): одна неподвижная точка
    правилом листа на текущих числах связанных шагов."""
    lines, r_lines = share_root_lines(eng), driver_root_lines(eng)
    if not lines and not r_lines:
        out["share_roots"] = {}
        return
    log = solve_share_roots(eng)
    kap = eng.value(SHARE_ROOTS) or {}
    out["share_roots"] = {ln: {"kappa": dict(kap[ln]), "rounds": log["rounds"], "converged": log["converged"]} for ln in lines}
    rho = eng.value(DRIVER_ROOTS) or {}
    out["driver_roots"] = {ln: {"rho": dict(rho[ln]), "rounds": log["rounds"], "converged": log["converged"]} for ln in r_lines}
    tail = (f"кругов неподвижной точки {len(log['rounds'])} (сдвиги " + " → ".join(f"{x:.1e}" for x in log["rounds"])
            + ("" if log["converged"] else "; НЕ СОШЛОСЬ") + ")")
    for ln in lines:
        k = kap[ln]
        say(f"{SHARE_ROOTS}.{ln}: κ 2026К3 {k['2026Q3']:+.6f}, 2027К1 {k['2027Q1']:+.6f}, 2028К1 {k['2028Q1']:+.6f}, 2029К4 "
            f"{k[SHARE_ROOT_LAST]:+.6f}, с 2030 — 0; {tail}")
    for ln in r_lines:
        r = rho[ln]
        say(f"{DRIVER_ROOTS}.{ln}: ρ 2026К3 {r['2026Q3']:+.6f}, 2027К1 {r['2027Q1']:+.6f}, 2028К1 {r['2028Q1']:+.6f}, 2029К4 "
            f"{r[SHARE_ROOT_LAST]:+.6f}, с 2030 — 0 (совместно с κ); {tail}")


def axis_share_root_lines(eng: Engine, ax: dict) -> list[str]:
    """Строки ключа Р8-6, чьи κ несёт связка: все пути κ строки (кварталы перехода) — несёт; ни одного — нет (κ конца печатается
    рядом); часть — остановка листа (конец связки вышел бы без части κ, класс 4)."""
    out = []
    paths = {str(p) for p in ax["paths"]}
    kap = book_opt(eng, SHARE_ROOTS) or {}
    for ln in share_root_lines(eng):
        keys = [f"{SHARE_ROOTS}.{ln}.{k}" for k in kap[ln] if k not in ("LT", "LT_from")]
        have = [k for k in keys if k in paths]
        if not have:
            continue
        if len(have) != len(keys):
            raise RuntimeError(f"ось «{ax['name']}» несёт часть путей κ строки {ln} ({len(have)} из {len(keys)}) — связка несёт все "
                               "кварталы перехода κ или ни одного (Р8-6, класс 4)")
        out.append(ln)
    return out


def axis_driver_root_lines(eng: Engine, ax: dict, kappa_carried: list[str]) -> list[str]:
    """Строки ключа Р9-1, чьи ρ несёт связка: все 14 путей ρ строки — несёт; ни одного — нет (ρ конца рядом); часть путей — остановка.
    Связка, несущая κ строки, несёт и ρ той же строки (одно правило, один шаг): κ без ρ или ρ без κ — остановка листа (класс 4)."""
    out = []
    paths = {str(p) for p in ax["paths"]}
    rho = book_opt(eng, DRIVER_ROOTS) or {}
    k_lines = share_root_lines(eng)
    for ln in driver_root_lines(eng):
        keys = [f"{DRIVER_ROOTS}.{ln}.{k}" for k in rho[ln] if k not in ("LT", "LT_from")]
        have = [k for k in keys if k in paths]
        if have and len(have) != len(keys):
            raise RuntimeError(f"ось «{ax['name']}» несёт часть путей ρ строки {ln} ({len(have)} из {len(keys)}) — связка несёт все "
                               "кварталы перехода ρ или ни одного (Р9-1, класс 4)")
        if ln in k_lines and bool(have) != (ln in kappa_carried):
            raise RuntimeError(f"ось «{ax['name']}» несёт " + ("ρ без κ" if have else "κ без ρ") + f" строки {ln} — связка несёт "
                               "κ и ρ строки вместе (одно правило, один шаг share_roots; Р9-1, класс 4)")
        if have:
            out.append(ln)
    return out


NOT_DERIVED_ENDS: set = set()           # Р12-9: пути κ/ρ связок, оставленные на концах числом книги запуска (печать один раз)


def end_share_roots(eng: Engine, ax: dict, vals: dict, aside: dict, end: str | None = None) -> None:
    """κ и ρ на конце связки тем же правилом центра (Р8-6, Р9-1, класс 4) одной неподвижной точкой на подменах конца
    (eng.overrides — конец): связка несёт пути — в её значения `vals`; не несёт — рядом (`aside`, для цены). Нет ключей — ничего.
    Затем — проверка на ЗАПИСАННЫХ числах конца (корни строк — с точностью записи, κ и ρ — 6 знаков): правило на них против
    записи и невязки (κ: E_M[H] − E_M[A]/A_0; ρ: N^ρ,M − E_M[D]/D_0) — в eng.kappa_ends и eng.rho_ends (допуск листа
    KAPPA_END_TOL = 5e-5, решения ведущего № 9, Р9-7; повторный вызов того же конца — заменяет)."""
    lines, r_lines = share_root_lines(eng), driver_root_lines(eng)
    # Р12-9 (решения ведущего № 12; поток book12): пути κ и ρ, которые связка несёт, а запуск их не выводит (вариант снимает корень
    # — k6_root_off — или ведомую книгу — insurance_liab_as_funds), остаются на конце числом книги запуска: ось меняет ровно
    # объявленный ключ (класс 4). Было — KeyError volumes.liability_driver_roots на концах связок (сухой перевывод отказывал)
    for p in ax.get("paths", []):
        p = str(p)
        if p in vals or not p.startswith((SHARE_ROOTS + ".", DRIVER_ROOTS + ".")):
            continue
        ln = p.split(".")[2]
        if (p.startswith(SHARE_ROOTS + ".") and ln not in lines) or (p.startswith(DRIVER_ROOTS + ".") and ln not in r_lines):
            vals[p] = float(book_opt(eng, p))
            if p not in NOT_DERIVED_ENDS:
                NOT_DERIVED_ENDS.add(p)
                if len(NOT_DERIVED_ENDS) == 1:
                    say(f"   Р12-9: пути κ/ρ связок, которые запуск не выводит (вариант), — на концах числом книги запуска: {p} …")
    if not lines and not r_lines:
        return
    carried = axis_share_root_lines(eng, ax)
    carried_r = axis_driver_root_lines(eng, ax, carried)
    solve_share_roots(eng)
    kap, rho = eng.value(SHARE_ROOTS) or {}, eng.value(DRIVER_ROOTS) or {}
    for ln in lines:
        got = {f"{SHARE_ROOTS}.{ln}.{k}": float(v) for k, v in kap[ln].items() if k not in ("LT", "LT_from")}
        (vals if ln in carried else aside).update(got)
    for ln in r_lines:
        got = {f"{DRIVER_ROOTS}.{ln}.{k}": float(v) for k, v in rho[ln].items() if k not in ("LT", "LT_from")}
        (vals if ln in carried_r else aside).update(got)
    saved = copy.deepcopy(eng.overrides)
    try:                                                     # Р9-7: правило κ и ρ на записанных (округлённых) числах конца
        for name, path in LINE_ROOT_PATHS.items():
            if path in eng.overrides:
                tr = eng.value(path)
                eng.overrides[path] = rounded_traj(name, tr, roots_of(name, tr))
        run = eng.grid()
        eng.link_line = bool(getattr(run.ctx.prep, "link_line", False) or getattr(run.ctx.prep, "k6_line", None) is not None)
        for ln in lines:
            traj, dev = kappa_of(eng, run, ln)
            row = {"axis": str(ax.get("name")), "end": end, "line": ln, "carried": ln in carried,
                   "rule_change": round(_kappa_change(dict(kap[ln]), traj), 9), "max_dev": None if dev is None else round(dev, 9)}
            eng.kappa_ends[(row["axis"], end, ln)] = row
        for ln in r_lines:
            traj, dev, jen = rho_of(eng, run, ln)
            row = {"axis": str(ax.get("name")), "end": end, "line": ln, "carried": ln in carried_r,
                   "rule_change": round(_kappa_change(dict(rho[ln]), traj), 9), "max_dev": round(dev, 9), "jensen": round(jen, 9)}
            eng.rho_ends[(row["axis"], end, ln)] = row
    finally:
        eng.overrides = saved


