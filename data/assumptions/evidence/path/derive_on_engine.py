def bisect(fn, lo: float, hi: float, steps: int = 60, tol: float = 1e-10) -> float:
    """Корень монотонной fn на [lo; hi] (Иллинойс)."""
    f_lo, f_hi = fn(lo), fn(hi)
    if f_lo == 0:
        return lo
    if f_hi == 0:
        return hi
    if f_lo * f_hi > 0:
        raise RuntimeError(f"на отрезке [{lo}; {hi}] корня нет: значения {f_lo:+.6f} и {f_hi:+.6f}")
    side = 0
    x = lo
    for _ in range(steps):
        x = (lo * f_hi - hi * f_lo) / (f_hi - f_lo)
        f_x = fn(x)
        if abs(f_x) < tol or abs(hi - lo) < tol:
            return x
        if f_x * f_hi > 0:
            hi, f_hi = x, f_x
            if side == -1:
                f_lo /= 2
            side = -1
        else:
            lo, f_lo = x, f_x
            if side == 1:
                f_hi /= 2
            side = 1
    return x


