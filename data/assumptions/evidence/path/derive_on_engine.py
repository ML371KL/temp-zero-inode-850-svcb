def _line_rule(run, prob: dict, lam: float, hist: dict, value, mult: bool) -> tuple[dict, dict]:
    """Корень формы строки (Р10-5) последовательным правилом на путях сетки `run`: индекс правила X^c_q = X^c_(q−4) × g(B^c_q /
    B^c_(q−4), w^M_q, λ, r_q), X_x = B_x / B_0 при x ≤ 0 (`hist` — B_x, x = −3…0); r_q — так, что E_M[X_q] = E_M[B_q] / B_0 до
    2029К4 (`prob` — вероятности слоя M): r_q = (E_M[B_q] / B_0) / E_M[G] − 1 при корне множителем (`mult`), (E_M[B_q] / B_0 −
    E_M[G]) / E_M[X_(q−4)] при корне слагаемым, G_c = X^c_(q−4) g(…, 0); r_q записывается 6 знаками и в рекурсию идёт записанным;
    с 2030 года 0 (LT 0, LT_from 2030). `value(c, q)` — B клетки в квартале q ≥ 1. g — `model.cell.link_growth` (одна функция с
    ядром). → (траектория r, {клетка: X по q} — индекс правила)."""
    from model.cell import link_growth
    tl = run.ctx.timeline
    wage = run.ctx.worlds[SHARE_ROOT_WORLD].wage
    q_end = tl.index(SHARE_ROOT_LAST)
    cells = [c for c in run.cells if prob[c.key] > 0]
    b0 = float(hist[0])
    B = {c.key: {**{x: float(hist[x]) for x in range(-3, 1)}, **{q: float(value(c, q)) for q in range(1, q_end + 1)}}
         for c in cells}
    X = {k: {x: B[k][x] / b0 for x in range(-3, 1)} for k in B}
    traj: dict = {}
    for q in range(1, q_end + 1):
        w = float(wage[q])
        g0 = {k: X[k][q - 4] * link_growth(B[k][q] / B[k][q - 4], w, lam, 0.0, mult) for k in X}
        eb = sum(prob[k] * B[k][q] for k in X) / b0
        eg = sum(prob[k] * g0[k] for k in X)
        r = round(eb / eg - 1 if mult else (eb - eg) / sum(prob[k] * X[k][q - 4] for k in X), 6)
        traj[tl.period(q)] = r
        for k in X:
            X[k][q] = X[k][q - 4] * link_growth(B[k][q] / B[k][q - 4], w, lam, r, mult)
    traj["LT"] = 0.0
    traj["LT_from"] = int(SHARE_ROOT_LAST[:4]) + 1
    return traj, X


def kappa_of(eng: Engine, run, line: str) -> tuple[dict, float | None]:
    """κ строки правилом листа на сетке `run` (запись 6 знаков) и невязка этой сетки max_q≤2029К4 |E_M[H_q] − E_M[A_q] / A_0|
    (None — ряда H в клетках нет: ключ строкой не читается). При форме строки (Р10-5; ядро читает франшизу строки ключом —
    prep.link_line) — правило `_line_rule` на базе строки A (ряд vol_ins / vol_fees, история — факты базы строки), λ — связь
    строки ядра, невязка — max_q |E_M[Φ_q] − E_M[A_q] / A_0| по ряду Φ ядра (vol_phi_<строка>)."""
    tl = run.ctx.timeline
    prob = market_prob(run)
    attr, row, nom = SHARE_ROOT_ROWS[line]
    base = getattr(run.ctx.prep, attr)
    if base is None:
        raise RuntimeError(f"κ строки {line}: у книги нет базы строки ({attr}) — ключ Р8-6 читается только при своей базе строки")
    if getattr(run.ctx.prep, "link_line", False):            # Р10-5: франшиза формой строки — корень г/г всей смеси темпов
        share_nom = (run.ctx.prep.share_nominal or {}).get(line)
        if share_nom is None:
            raise RuntimeError(f"κ строки {line}: франшиза строки ключом не читается (форма строки, Р10-5)")
        lam, _, phi = share_nom
        traj, _ = _line_rule(run, prob, float(lam), base.hist, lambda c, q: c.quarters[row][q], run.ctx.prep.root_mult)
        q_end = tl.index(SHARE_ROOT_LAST)
        a0 = float(base.hist[0])
        dev = max(abs(float(eng.levels.expect(run, prob, phi, q)) - float(eng.levels.expect(run, prob, row, q)) / a0)
                  for q in range(1, q_end + 1))
        return traj, dev
    wage = run.ctx.worlds[SHARE_ROOT_WORLD].wage
    q_end = tl.index(SHARE_ROOT_LAST)
    em = {x: float(base.hist[x]) for x in range(-3, 1)}
    for q in range(1, q_end + 1):
        em[q] = float(eng.levels.expect(run, prob, row, q))
    traj: dict = {}
    for q in range(1, q_end + 1):
        traj[tl.period(q)] = round(em[q] / em[q - 4] / (1 + float(wage[q])) - 1, 6)
    traj["LT"] = 0.0
    traj["LT_from"] = int(SHARE_ROOT_LAST[:4]) + 1
    dev = None
    if nom in run.cells[0].quarters:
        dev = max(abs(float(eng.levels.expect(run, prob, nom, q)) - em[q] / em[0]) for q in range(1, q_end + 1))
    return traj, dev


