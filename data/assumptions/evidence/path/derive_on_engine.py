def compile_mix_local(eng: Engine, spec: dict, path: str) -> dict:
    """Смесь баз с долями на якоре (К2б, notes/core-pass3/spec.yaml K2b.formulas.compile) → веса книг: ω_b = Σ_k s_k ω^k_b / D^k_0,
    D^k_0 = Σ_b ω^k_b E_b,0 (ОСТАТКИ якоря на конец квартала якоря). Компонента loans — веса 1 на кредитных книгах; словарь —
    как есть; funds, iea, nominal — листом не поддержаны (база «books» листа — только кредитные книги). Σ s ≠ 1 — отказ."""
    mix = spec.get("mix") or {}
    if not mix:
        raise RuntimeError(f"{path}: пустая смесь баз")
    total = sum(float(c["share"]) for c in mix.values())
    if abs(total - 1.0) > 1e-9:
        raise RuntimeError(f"{path}: сумма долей смеси {total:.12g} ≠ 1 (К2б)")
    e0 = {b: float(v["v"]) for b, v in eng.facts.file("balance")["books"].items()}
    out: dict = {}
    for name, comp in mix.items():
        base = comp["base"]
        if isinstance(base, str):
            if base != "loans":
                raise RuntimeError(f"{path}.mix.{name}: компонента {base!r} листом не поддержана (только кредитные книги)")
            wk = {b: 1.0 for b in RETAIL_BOOKS + (CORP_BOOK,)}
        else:
            wk = {str(b): float(x) for b, x in base.items() if float(x) > 0}
        if set(wk) - set(RETAIL_BOOKS + (CORP_BOOK,)):
            raise RuntimeError(f"{path}.mix.{name}: книги {sorted(set(wk) - set(RETAIL_BOOKS + (CORP_BOOK,)))} — не кредитные")
        d0 = sum(wk[b] * e0[b] for b in wk)
        if not d0 > 0:
            raise RuntimeError(f"{path}.mix.{name}: уровень компоненты на якоре {d0:g} ≤ 0")
        for b, x in wk.items():
            out[b] = out.get(b, 0.0) + float(comp["share"]) * x / d0
    return out


def compile_mix(eng: Engine, spec: dict, path: str) -> dict:
    """Смесь баз → веса книг ОДНОЙ функцией с ядром (класс 1): если ядро несёт model.cell.resolve_line_base (проход ядра 3, К2б),
    веса — её; своя компиляция листа сверяется с ней (отказ при расхождении). Ядро без К2б (p3 круга 3) смесь не читает — тогда
    только своя компиляция (лист готов к ключу; на ядре без К2б книга со смесью не загрузится)."""
    own = compile_mix_local(eng, spec, path)
    try:
        from model.cell import resolve_line_base
    except ImportError:
        return own
    from model.book import anchor_facts, book_roles
    book = eng.current()
    books = book.get("nii.books")
    core = resolve_line_base(book, path, roles=book_roles(books), balances=anchor_facts(eng.facts, books).balances)
    if not isinstance(core, dict):
        raise RuntimeError(f"{path}: resolve_line_base ядра вернула {core!r}, лист компилирует смесь в веса книг")
    core = {str(b): float(x) for b, x in core.items() if float(x) > 0}
    scale_c, scale_o = sum(core.values()), sum(own.values())
    off = {b: (core.get(b), own.get(b)) for b in set(core) | set(own)
           if abs(core.get(b, 0.0) / scale_c - own.get(b, 0.0) / scale_o) > 1e-12}
    if off:
        raise RuntimeError(f"{path}: веса смеси у ядра и листа разные (класс 1): {off}")
    return core


def sync_line_bases(eng: Engine) -> None:
    """База уровня комиссий и страхования = база их роста в ядре (К2, класс 4): ключ строки или volumes.link_base. Читает
    подмены листа (концы осей баз). Смесь баз (К2б: {mix: {имя: {share, base}}}) — веса книг компиляцией (compile_mix)."""
    LINE_WEIGHTS.clear()
    link = str(eng.value("volumes.link_base") or "loans")
    for name, path in LINE_BASE_PATHS.items():
        spec = book_opt(eng, path)
        spec = link if spec is None else spec
        if isinstance(spec, dict) and "mix" in spec:
            spec = compile_mix(eng, spec, path)
        if isinstance(spec, dict):
            w = {str(b): float(x) for b, x in spec.items() if float(x) > 0}
            if not w or set(w) - set(RETAIL_BOOKS + (CORP_BOOK,)):
                raise RuntimeError(f"{path}: база строки по весам — листом поддержаны только кредитные книги, получено {sorted(w)}")
            LINE_WEIGHTS[name] = normalized_line_weights(eng, w)
            LEVELS[name]["base"] = "books"
        elif str(spec) == "loans":
            LEVELS[name]["base"] = "loans"
        elif str(spec) == "iea":
            LEVELS[name]["base"] = "iea"
        else:
            raise RuntimeError(f"{path} = {spec!r}: база уровня строки листом не поддержана (класс 4 — уровень к той же базе, что рост)")


def line_books_end(eng: Engine, name: str, p: str) -> float:
    """База строки по весам кредитных книг на конец квартала фактов `p` (К2): Σ w_b × остаток книги; концы без остатков книг —
    группами по примечанию МСФО (розница — retail_gross_bn, юрлица — кредиты фактов минус розница)."""
    w = LINE_WEIGHTS[name]
    bal = eng.facts.file("balance")
    anchor = str(eng.facts.plain("anchor", "period"))
    books = (bal["books"] if p == anchor else bal["history"][p].get("books")) or {}
    if all(b in books for b in w):
        return sum(w[b] * float(books[b]["v"]) for b in w)
    split = {r["period"]: r for r in csv.DictReader(LOAN_SPLIT.open(encoding="utf-8"))}
    if p not in split:
        raise RuntimeError(f"база строки {name}: на конце {p} нет остатков кредитных книг и доли примечания МСФО")
    wr = {round(w.get(b, 0.0), 12) for b in RETAIL_BOOKS}
    if len(wr) != 1:
        raise RuntimeError(f"база строки {name}: веса розничных книг не равны — конец {p} без остатков книг не считается")
    retail = float(split[p]["retail_gross_bn"])
    return wr.pop() * retail + w.get(CORP_BOOK, 0.0) * (float(bal["history"][p]["loans"]["v"]) - retail)


def avg_base(eng: Engine, run, prob: dict, year: int, base: str, name: str | None = None) -> float:
    """Средняя база уровня строки года: активы, валовые кредиты или смешанная L + MIX_W × (A − L) (решения № 2, Б2); у базы
    по весам кредитных книг (К2) — средняя за кварталы ряда vol_fees / vol_ins клетки."""
    if base == "assets":
        return avg_assets(eng, run, prob, year)
    if base == "weighted":
        qs = [q for q in run.ctx.timeline.quarters_of_year(year) if q >= 1]
        return sum(float(eng.levels.expect(run, prob, "vol_opex", q)) for q in qs) / len(qs)
    if base in ("books", "iea"):
        qs = [q for q in run.ctx.timeline.quarters_of_year(year) if q >= 1]
        return sum(float(eng.levels.expect(run, prob, LINE_ROWS[name], q)) for q in qs) / len(qs)
    loans = avg_loans(eng, run, prob, year)
    if base == "loans":
        return loans
    if base == "mix":
        return loans + MIX_W * (avg_assets(eng, run, prob, year) - loans)
    raise RuntimeError(f"незнакомая база уровня строки {base!r}")


def level_of(eng: Engine, run, prob: dict, name: str, year: int) -> float:
    """Строка к своей базе года (годовой поток — сумма ожидаемых кварталов года; база — `LEVELS[name]['base']`). Одна функция
    у корней центра, LT, концов осей и печати (класс 4)."""
    tl = run.ctx.timeline
    qs = [q for q in tl.quarters_of_year(year) if q >= 1]
    total = sum(abs(float(eng.levels.expect(run, prob, LEVELS[name]["flow"], q))) for q in qs)
    return total * 4 / len(qs) / avg_base(eng, run, prob, year, LEVELS[name]["base"], name)


def _quarter_days(period: str) -> int:
    import datetime as _dt
    y, q = int(period[:4]), int(period[-1])
    start = _dt.date(y, 3 * q - 2, 1)
    end = _dt.date(y + (q == 4), (3 * q) % 12 + 1, 1)
    return (end - start).days


