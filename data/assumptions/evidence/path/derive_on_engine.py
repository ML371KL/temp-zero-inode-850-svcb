def _near_traj(eng: Engine, tl, d: float, nd: int | None = None) -> dict:
    """Сдвиг затухает линейно: d в 3К2026, ноль в 1К года после последнего года сдвига. `nd` — знаков записи
    квартальных ключей (ключ года — среднее записанных кварталов, MODEL §0.4)."""
    q3 = tl.index(NEAR_PERIOD)
    q_end = tl.index(f"{NEAR_LAST_YEAR + 1}Q1")
    traj: dict = {}
    for y in range(int(NEAR_PERIOD[:4]), NEAR_LAST_YEAR + 1):
        vals = []
        for qn in range(1, 5):
            p = f"{y}Q{qn}"
            q = tl.index(p)
            if q < q3:
                continue
            v = d * (q_end - q) / (q_end - q3)
            if nd is not None:
                v = round(v, nd)
            traj[p] = v
            vals.append(v)
        mean = sum(vals) / len(vals)
        traj[str(y)] = mean if nd is None else round(mean, nd + 2)
    traj.update({"LT": 0.0, "LT_from": NEAR_LAST_YEAR + 1})
    return traj


def near_target(eng: Engine) -> float:
    """Нау-каст 3К2026 опр. банка → ЧПМ ядра (упр. базис ядра = движок / b): ставка книги страховых — ставка якоря."""
    t = bank_terms(eng)
    rate = float(eng.facts.need("nii_books", f"books.{INS_BOOK}.rate_anchor"))
    return (NEAR_BANK * t["R"] - rate * t["l_ins"]) / t["b"]


def near_expect(eng: Engine, run, q: int) -> float:
    """ЧПМ квартала `q` (упр. ядра) — ожидание слоя «свой взгляд» по клеткам сетки (решения ведущего № 9, класс 2: квартал
    нау-каста — не условия одной клетки; ключевая 2П2026 у миров почти одна; было — модальная клетка)."""
    return own_expect(run, lambda c: nim_mgmt_q(eng, c, q))


def step_near(eng: Engine, out: dict) -> None:
    ctx, cell = eng.cell()
    tl = ctx.timeline
    q3 = tl.index(NEAR_PERIOD)
    want = near_target(eng)
    have = eng.value("regimes.near_nim_shift")
    d = float(have.get(NEAR_PERIOD, 0.0))
    free = None
    for i in range(40):
        eng.overrides["regimes.near_nim_shift"] = _near_traj(eng, tl, d)
        got = near_expect(eng, eng.grid(), q3)
        if free is None and i == 0 and abs(d) < 1e-15:
            free = got
        miss = want - got
        if abs(miss) < 2e-9:
            break
        d += miss * float(eng.bridge.nim_value)
    traj = _near_traj(eng, tl, d)
    eng.overrides["regimes.near_nim_shift"] = traj
    eng.near_d, eng.near_fresh = d, True
    run = eng.grid()
    ctx, cell = eng.cell()
    last = min(tl.Q, tl.index(f"{NEAR_LAST_YEAR + 1}Q4"))
    path = {tl.period(q): round(near_expect(eng, run, q), 5) for q in range(1, last + 1)}
    modal = {tl.period(q): round(nim_mgmt_q(eng, cell, q), 5) for q in range(1, last + 1)}
    out["near"] = {"target_bank": NEAR_BANK, "target_core": round(want, 6), "shift_q3": round(d, 6), "layer": OWN_LAYER,
                   "nim_mgmt_path": path, "nim_mgmt_path_modal_cell": modal, "free_q3": None if free is None else round(free, 6)}
    say(f"regimes.near_nim_shift: {NEAR_PERIOD} {d:+.5f} (нау-каст {100 * NEAR_BANK:.2f} % опр. банка = {100 * want:.3f} % ядра — ожидание слоя "
        f"«свой взгляд»), затухание к 0 в {NEAR_LAST_YEAR + 1}Q1; ЧПМ ожидания слоя, упр. ядра: "
        + ", ".join(f"{p} {100 * v:.2f}" for p, v in list(path.items())[:6]) + f" … (модальная клетка {NEAR_PERIOD} {100 * modal[NEAR_PERIOD]:.3f})")


