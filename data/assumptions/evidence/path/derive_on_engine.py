def flat(eng: Engine) -> dict[str, tuple[float, float]]:
    nim = float(eng.value(NIM_KEY))
    out: dict[str, tuple[float, float]] = {}
    for path in ("nii.sigma0_split", "nii.phi_split"):
        out[path] = (float(eng.value(path)), 1.0)
    for k, v in eng.value("regimes.near_nim_shift").items():
        if k != "LT_from":
            out[f"regimes.near_nim_shift.{k}"] = (float(v), nim)
    for name in LEVEL_ORDER:
        for k, v in eng.value(LEVELS[name]["path"]).items():
            if k != "LT_from":
                out[f"{LEVELS[name]['path']}.{k}"] = (float(v), 1.0 + float(v))
    kap = book_opt(eng, SHARE_ROOTS) or {}
    for ln in share_root_lines(eng):                          # Р8-6: κ — в сходимости связанных шагов
        for k, v in kap[ln].items():
            if k != "LT_from":
                out[f"{SHARE_ROOTS}.{ln}.{k}"] = (float(v), 1.0 + float(v))
    rho = book_opt(eng, DRIVER_ROOTS) or {}
    for ln in driver_root_lines(eng):                         # Р9-1: ρ — в сходимости связанных шагов (вместе с κ)
        for k, v in rho[ln].items():
            if k != "LT_from":
                out[f"{DRIVER_ROOTS}.{ln}.{k}"] = (float(v), 1.0 + float(v))
    return out


def worst_change(a: dict, b: dict) -> tuple[float, str]:
    best = (0.0, "")
    for k, (v, scale) in b.items():
        old = a.get(k, (None, None))[0]
        change = float("inf") if old is None else abs(v - old) / abs(scale)
        if change > best[0]:
            best = (change, k)
    return best


def written(eng: Engine, steps: list[str]) -> dict:
    """Выведенные ключи с точностью записи шаблона (все — и в фазе после центра: там они приходят записью центра)."""
    keys: dict = {}
    keys[NIM_KEY] = round(float(eng.value(NIM_KEY)), 6)
    keys["nii.transmission.target"] = round(float(eng.value("nii.transmission.target")), 6)
    keys["capital.rwa.density"] = {k: float(v) for k, v in eng.value("capital.rwa.density").items()}
    keys["capital.n20.deductions_anchor"] = float(eng.value("capital.n20.deductions_anchor"))
    keys["capital.n11.deductions_anchor"] = float(eng.value("capital.n11.deductions_anchor"))
    for name in eng.value("nii.books"):
        keys[f"nii.books.{name}.spread"] = dict(eng.value(f"nii.books.{name}.spread"))
    keys["nii.sigma0_split"] = float(eng.value("nii.sigma0_split"))
    keys["nii.phi_split"] = float(eng.value("nii.phi_split"))
    if getattr(eng, "near_fresh", False):                     # шаг near считал в этом запуске — запись из его сдвига
        ctx = eng.make_context(eng.current(), eng.facts)
        keys["regimes.near_nim_shift"] = _near_traj(eng, ctx.timeline, eng.near_d, nd=6)
    else:                                                       # записанный путь (книги или записи центра) — как есть
        keys["regimes.near_nim_shift"] = dict(eng.value("regimes.near_nim_shift"))
    for name in LEVEL_ORDER:
        path = LEVELS[name]["path"]
        keys[path] = rounded_traj(name, eng.value(path), roots_of(name, eng.value(path)))
    kap = book_opt(eng, SHARE_ROOTS) or {}
    if kap:                                                   # Р8-6: κ строк — 6 знаков, весь ключ одним путём (подмена листа)
        keys[SHARE_ROOTS] = {str(ln): {str(k): (int(v) if k == "LT_from" else round(float(v), 6)) for k, v in tr.items()}
                             for ln, tr in kap.items()}
    rho = book_opt(eng, DRIVER_ROOTS) or {}
    if rho:                                                   # Р9-1: ρ строк — 6 знаков, весь ключ одним путём (подмена листа)
        keys[DRIVER_ROOTS] = {str(ln): {str(k): (int(v) if k == "LT_from" else round(float(v), 6)) for k, v in tr.items()}
                              for ln, tr in rho.items()}
    return keys


def apply_written(eng: Engine, keys: dict) -> None:
    """Записанные (округлённые) ключи — в подмены листа."""
    for path, v in keys.items():
        eng.overrides[path] = copy.deepcopy(v)
    eng.near_fresh = False                                      # записанные ключи — дальше их, а не сдвиг шага


def frozen_check(eng: Engine, out: dict) -> None:
    book = eng.current()
    ctx, cell = eng.cell()
    tl = ctx.timeline
    world, key = level_world(book), float(book.get(NIM_KEY))
    tr = eng.solve(book, eng.facts, eng.bridge)
    stationary = float(eng.bridge.to_mgmt_nim(float(tr.nss[world])))
    t = bank_terms(eng, book)
    af = eng.anchor_facts(eng.facts, book.get("nii.books"))
    pic = level_picture(eng)
    last = str(tl.last_year)
    lv = {}
    probes: dict = {}
    for name in LEVEL_ORDER:
        cfg = LEVELS[name]
        years = [g[-1][:4] for g in cfg["groups"]] + [last]
        goal = eng.level_goals[name] if name in eng.level_goals else level_goal(eng, name)
        lv[name] = {y: round(pic[name]["path"][y] - goal, 7) for y in years}
        lv[name]["anchor_growth_miss"] = round(pic[name]["anchor_growth"] - anchor_goal(eng, ctx, name)["goal"], 7)
        years_tail = range(int(cfg["groups"][-1][-1][:4]), tl.last_year + 1)
        tail = [pic[name]["path"][str(y)] for y in years_tail]
        link = line_link(eng, name)
        if link >= 1.0:
            lv[name]["max_tail_dev"] = round(max(abs(x - goal) for x in tail), 7)
            continue
        # Р7-3 (решения ведущего № 7): при связи < 1 отношение строки к своей базе после 2029 года ДРЕЙФУЕТ на (1 − связь) × (рост
        # зарплат − рост базы) — это суждение о связи, не корень. Проверка «стационар без корня» судит отсутствие корня после 2029 года
        # на пробе со связью 1 (те же корни 2026–2029; отношение за 2029 годом неподвижно — к значению пробы в 2029 году), а отношение
        # строки к своей базе в условиях окна (слой M) — в году корня (строка «год корня» выше: 2029 = центру); дрейф отношения в
        # слое M 2030–2036 печатается рядом и судится диапазоном свидетельств уровня (концы оси уровня строки).
        probe = probes.setdefault(name, level_picture(eng, {LINK_PATHS[name]: 1.0}))[name]["path"]
        tail_p = [probe[str(y)] for y in years_tail]
        lv[name]["max_tail_dev"] = round(max(abs(x - tail_p[0]) for x in tail_p), 7)
        lv[name]["link"] = link
        lv[name]["tail_drift"] = {str(y): round(x - goal, 7) for y, x in zip(years_tail, tail)}
        lo_e, hi_e = level_ends(eng, name)                     # концы оси уровня строки — диапазон свидетельств (правило ends_rule)
        lv[name]["tail_range"] = [round(lo_e, 7), round(hi_e, 7)]
        lv[name]["tail_outside_range"] = round(max(max(lo_e - x, x - hi_e, 0.0) for x in tail), 7)
    sr, dr = {}, {}
    lines_k, lines_r = share_root_lines(eng), driver_root_lines(eng)
    if lines_k or lines_r:                                     # Р8-6: невязка κ на записанных числах — E_M[H] против E_M[A] / A_0
        run_k = eng.grid()
        for ln in lines_k:
            traj_k, dev_k = kappa_of(eng, run_k, ln)
            sr[ln] = {"max_dev": None if dev_k is None else round(dev_k, 9),
                      "rule_change": round(_kappa_change(dict(eng.value(SHARE_ROOTS)[ln]), traj_k), 9)}
        for ln in lines_r:                                     # Р9-1: невязка ρ — N^ρ,M против E_M[D] / D_0; Йенсен — печать формы
            traj_r, dev_r, jen_r = rho_of(eng, run_k, ln)
            dr[ln] = {"max_dev": round(dev_r, 9), "jensen": round(jen_r, 9),
                      "rule_change": round(_kappa_change(dict(eng.value(DRIVER_ROOTS)[ln]), traj_r), 9)}
    out["frozen_check"] = {"nim_stationary": round(stationary, 9), "nim_stationary_ok": abs(stationary - key) <= 1e-9,
                           "nim_bank_level_world": round(to_bank(t, float(tr.nss[world]), world), 6),
                           "near_q3": round(near_expect(eng, eng.grid(), tl.index(NEAR_PERIOD)), 7),
                           "near_q3_modal_cell": round(nim_mgmt_q(eng, cell, tl.index(NEAR_PERIOD)), 7), "near_target": round(near_target(eng), 7),
                           "near_after": round(float(eng.value("regimes.near_nim_shift").get(f"{NEAR_LAST_YEAR + 1}Q1", 0.0)), 9),
                           "anchor_n20_gap": round(float(cell.quarters["n20"][0]) - float(af.n20), 7),
                           "anchor_n11_gap": round(float(cell.quarters["n11"][0]) - float(af.n11_bank), 7),
                           "anchor_rwa_gap": round(float(cell.quarters["rwa"][0]) - float(af.basel_rwa), 4),
                           "levels": lv, "share_roots": sr, "driver_roots": dr}
    say(f"на записанных ключах: стационар мира {world} {100 * stationary:.4f} % ключа ({'= ключу' if abs(stationary - key) <= 1e-9 else 'НЕ РАВЕН КЛЮЧУ'}), "
        f"опр. банка {100 * out['frozen_check']['nim_bank_level_world']:.3f} %; ЧПМ 3К2026 {100 * out['frozen_check']['near_q3']:.3f} % (цель "
        f"{100 * out['frozen_check']['near_target']:.3f}); якорь: Н1.0 {out['frozen_check']['anchor_n20_gap']:+.1e}, Н1.2 {out['frozen_check']['anchor_n11_gap']:+.1e}; "
        + "; ".join(f"{n}: " + ", ".join(f"{k} {v:+.1e}" for k, v in d.items() if isinstance(v, (int, float))) for n, d in lv.items()))
    phi, psi = (getattr(ctx.prep, "link_line", False), getattr(ctx.prep, "k6_line", None) is not None)   # Р10-5: форма строки
    for ln, d in sr.items():
        say(f"κ {ln} на записанных ключах: max|{'E_M[Φ]' if phi else 'E_M[H]'} − E_M[A]/A_0| до {SHARE_ROOT_LAST} {d['max_dev']}, "
            f"правило против записи {d['rule_change']}")
    for ln, d in dr.items():
        say(f"ρ {ln} на записанных ключах: max|{'E_M[Ψ]' if psi else 'N^ρ,M'} − E_M[D]/D_0| до {SHARE_ROOT_LAST} {d['max_dev']}, "
            f"правило против записи {d['rule_change']}; {'книга' if psi else 'Йенсен'} E_M[К6]/К6_0 ÷ E_M[D]/D_0 − 1 до {d['jensen']}")


